DROP VIEW IF EXISTS "main"."vw_DUPLICATES";
CREATE VIEW "vw_DUPLICATES" AS WITH RECORDS AS
(SELECT
StockCode,
InvoiceNo,
CustomerID
FROM SALES)
,
DUPLICATE_RECORDS AS
(SELECT
	StockCode,
	InvoiceNo,
	CustomerID,
    COUNT(*) AS RecordCount
FROM 
RECORDS
GROUP BY
	StockCode,
	InvoiceNo,
	CustomerID
HAVING COUNT(*) > 1
ORDER BY RecordCount DESC)

SELECT * FROM SALES
INNER JOIN DUPLICATE_RECORDS ON 
	SALES.StockCode = DUPLICATE_RECORDS.StockCode AND
	SALES.InvoiceNo = DUPLICATE_RECORDS.InvoiceNo AND
	COALESCE(SALES.CustomerID,'') = COALESCE(DUPLICATE_RECORDS.CustomerID,'')
ORDER BY SALES.StockCode DESC